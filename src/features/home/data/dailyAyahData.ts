export const getCalendarDateKey = (date = new Date()): string => {
  const y = date.getFullYear();
  const m = String(date.getMonth() + 1).padStart(2, '0');
  const d = String(date.getDate()).padStart(2, '0');
  return `${y}-${m}-${d}`;
};

const hashDateKey = (str: string): number => {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    const char = str.charCodeAt(i);
    hash = (hash << 5) - hash + char;
    hash |= 0;
  }
  return Math.abs(hash);
};

export const getDailyAyah = (dateKey = getCalendarDateKey()): DailyAyahItem => {
  const total = INSPIRATIONAL_DAILY_AYAHS.length;
  if (total === 0) {
    throw new Error('No inspirational daily ayahs defined');
  }
  const hash = hashDateKey(dateKey);
  const index = hash % total;
  return INSPIRATIONAL_DAILY_AYAHS[index];
};
